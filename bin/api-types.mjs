#!/usr/bin/env node

import fs from "node:fs";
import openapiTS from "openapi-typescript";
import { format } from "oxfmt";
import ts from "typescript";

const services = process.argv[2].split(",");

const UUID = ts.factory.createTypeReferenceNode(ts.factory.createIdentifier("UUID"));
const NULL = ts.factory.createLiteralTypeNode(ts.factory.createNull());

const isEmpty = (node) =>
  ts.isTypeAliasDeclaration(node) &&
  ts.isTypeReferenceNode(node.type) &&
  ts.isIdentifier(node.type.typeName) &&
  node.type.typeName.text === "Record" &&
  node.type.typeArguments?.length === 2 &&
  node.type.typeArguments[1].kind === ts.SyntaxKind.NeverKeyword;

await Promise.all(
  services.map(async (service) => {
    const output = await openapiTS(`${service}/doc`, {
      transform(schemaObject) {
        if ("format" in schemaObject && schemaObject.format === "uuid") {
          return schemaObject.nullable ? ts.factory.createUnionTypeNode([UUID, NULL]) : UUID;
        }
        return null;
      },
    });
    const path = `src/__definitions__/${service.replace("https://", "")}-definitions.ts`;
    const printer = ts.createPrinter({});
    const resultFile = ts.createSourceFile(path, "", ts.ScriptTarget.Latest);
    const result = output
      .filter((node) => !isEmpty(node))
      .map((node) => printer.printNode(ts.EmitHint.Unspecified, node, resultFile))
      .join("\n\n");
    fs.writeFileSync(
      path,
      (
        await format(
          path,
          `// Autogenerated by two-stroke

${fs.readFileSync("src/__definitions__/type-definitions.ts", "utf8")}

${result}`,
          { parser: "typescript", printWidth: 100 },
        )
      ).code,
    );
  }),
);
